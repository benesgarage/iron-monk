"""Concatenate the public iron-monk docs into a single LLM-ingestible file.

Run via ``make llms`` from the repo root. Writes ``docs/llms-full.txt``.

The page list mirrors the section order in ``docs/llms.txt`` so the two
artifacts stay in lockstep. Order matters: agents reading top-to-bottom expect
quickstart -> concepts -> catalog -> advanced -> integrations -> reference.

Internal maintenance tooling. Not shipped in the wheel. Consumers never run it.
"""

