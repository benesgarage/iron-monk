_YAML_FRONT_MATTER = re.compile(r"\A---\n.*?\n---\n", re.DOTALL)


def _read(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    return _YAML_FRONT_MATTER.sub("", text).rstrip() + "\n"


def main() -> None:
    parts: list[str] = [
        "# iron-monk - full docs (flat)\n",
        (
            "> Concatenated full documentation for iron-monk, "
            "in canonical reading order. Generated by support/build_llms.py - "
            "do not hand-edit. For a navigable index see llms.txt; for a "
            "token-trimmed digest see llms-ctx.txt.\n"
        ),
    ]
    for title, path in PAGES:
        if not path.exists():
            raise SystemExit(f"missing doc page: {path}")
        parts.append(f"\n\n---\n\n# {title}\n\n_Source: `{path.relative_to(ROOT)}`_\n\n")
        parts.append(_read(path))

    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes, {sum(1 for _ in OUT.open()):,} lines)")


if __name__ == "__main__":
    main()